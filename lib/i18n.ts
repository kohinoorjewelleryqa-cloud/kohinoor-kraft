/** Picks the right language field, falling back to English: pick(design, "name", "ar"). */
export function pick<T extends Record<string, unknown>>(o: T, field: string, lang: Lang): string {
  const v = o[`${field}_${lang}`] ?? o[`${field}_en`];
  return typeof v === "string" ? v : "";
}
/** Builds a link in the current language: href("ar", "/designs") → "/ar/designs". */
export const href = (lang: Lang, path = "") => `/${lang}${path === "/" ? "" : path}`;

